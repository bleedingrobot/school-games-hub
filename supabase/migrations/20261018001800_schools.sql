-- Maths focus F.2, part 1 of 3: schools.
--
-- The hub is still one website and one database, but every account now belongs to a school.
-- Douglas Park becomes school number 1 and everything already saved stays in it (every row
-- belongs to a student, and every student is moved into school 1 here).
--
-- What changes in the three locks (see README, "Security"):
--   1. Google: unchanged (the website only hints at school accounts; it never decides).
--   2. Sign-up hook + trigger: "is it a Douglas Park email?" becomes "is the email's domain in
--      school_domains for an active school?". An unknown domain still can't make an account.
--   3. Row rules: every read also checks school (my_school(), added to the rules in part 3).
--
-- Roles: student, teacher (their own classes), school admin (a teacher with profiles.school_admin;
-- everyone in their school) and site owner (site_owners; adds schools, sees no student data).
-- A school admin is still role = 'teacher', so every existing "is this a teacher?" check keeps working.

-- ---------------------------------------------------------------------------
-- Schools and the email domains they sign in with
-- ---------------------------------------------------------------------------

create table public.schools (
  id integer generated by default as identity primary key,
  name text not null check (name ~ '^[A-Za-zĀāĒēĪīŌōŪū0-9][A-Za-zĀāĒēĪīŌōŪū0-9 .''-]{1,59}$'),
  active boolean not null default true,
  -- The date the school's board approved the hub (its own copy of PRIVACY-SUMMARY.md). Null until then.
  board_approved_on date,
  -- A teacher the site owner can contact. Filled in with owner_set_school_contact().
  contact_teacher uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.school_domains (
  domain text primary key check (domain = lower(domain) and domain ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$'),
  school_id integer not null references public.schools (id) on delete cascade
);
create index school_domains_school on public.school_domains (school_id);

-- Douglas Park is school number 1.
insert into public.schools (id, name) overriding system value values (1, 'Douglas Park School');
select setval(pg_get_serial_sequence('public.schools', 'id'), 1);
insert into public.school_domains (domain, school_id) values ('douglaspark.school.nz', 1);

alter table public.schools enable row level security;
alter table public.school_domains enable row level security;
revoke all on public.schools, public.school_domains from anon, authenticated;
-- No policies and no grants: the website reads these only through the functions below.

-- ---------------------------------------------------------------------------
-- Every profile belongs to a school, and a student can never change it
-- ---------------------------------------------------------------------------

alter table public.profiles add column school_id integer references public.schools (id);
update public.profiles set school_id = 1 where school_id is null;
alter table public.profiles alter column school_id set not null;
create index profiles_school on public.profiles (school_id);

-- A school admin is a teacher who can also see and change things school-wide.
alter table public.profiles add column school_admin boolean not null default false;
alter table public.profiles add constraint profiles_admin_is_teacher check (not school_admin or role = 'teacher');

-- Nobody changes a person's school once it is set, not even by mistake in a later function.
create function public.keep_profile_school()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.school_id is distinct from old.school_id then
    raise exception 'A player''s school can''t be changed.' using errcode = '42501';
  end if;
  return new;
end;
$$;
create trigger keep_profile_school before update on public.profiles
for each row execute function public.keep_profile_school();

-- ---------------------------------------------------------------------------
-- Lock 2: which school does this email belong to?
-- ---------------------------------------------------------------------------

-- The school whose (active) domain list has this email's domain, or null.
create function public.school_for_email(email text)
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select d.school_id
  from public.school_domains d
  join public.schools s on s.id = d.school_id
  where s.active
    and d.domain = lower(substring(email from '^[^@\s]+@([^@\s]+)$'))
$$;

-- Same name and meaning as before ("is this a school email?"), but any active school's domain counts.
create or replace function public.is_school_email(email text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$ select public.school_for_email(email) is not null $$;

-- The one-school function is gone: the domain list is the school_domains table now.
drop function public.school_domain();

-- Every new account gets a profile straight away, in the school its email belongs to.
create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  home integer := public.school_for_email(new.email);
begin
  if home is null then
    raise exception 'Please sign in with your school Google account.' using errcode = '42501';
  end if;
  insert into public.profiles (id, display_name, school_id) values (new.id, public.pick_display_name(), home);
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Lock 3 helpers: who am I, and which school am I in?
-- ---------------------------------------------------------------------------

-- The signed-in student's or teacher's school. Null for anyone who isn't a school user.
create function public.my_school()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select p.school_id from public.profiles p where p.id = auth.uid() and public.is_school_user()
$$;

-- Is this player in my school? (False for a stranger, a missing player, or when I'm not signed in.)
create function public.same_school(other uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select p.school_id from public.profiles p where p.id = other) = public.my_school(), false)
$$;

create function public.is_school_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_teacher() and exists (
    select 1 from public.profiles where id = auth.uid() and school_admin
  )
$$;

create table public.site_owners (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.site_owners enable row level security;
revoke all on public.site_owners from anon, authenticated;

create function public.is_site_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_school_user() and exists (select 1 from public.site_owners where user_id = auth.uid())
$$;

create function public.require_school_admin()
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_school_admin() then
    raise exception 'Only a school admin can do that.' using errcode = '42501';
  end if;
end;
$$;

create function public.require_site_owner()
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_site_owner() then
    raise exception 'Only the site owner can do that.' using errcode = '42501';
  end if;
end;
$$;

-- Profiles: only people in my own school, and hidden ones only for teachers (part 3 narrows
-- teachers to their own classes).
drop policy "School users can see visible profiles, their own, or all if a teacher" on public.profiles;
create policy "School users can see profiles in their own school"
on public.profiles for select to authenticated
using (
  public.is_school_user()
  and school_id = (select public.my_school())
  and (not hidden or id = auth.uid() or public.is_teacher())
);

-- ---------------------------------------------------------------------------
-- Things a person can ask about their own school
-- ---------------------------------------------------------------------------

create function public.my_school_info()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object('id', s.id, 'name', s.name, 'admin', public.is_school_admin())
  from public.schools s where s.id = public.my_school()
$$;

-- ---------------------------------------------------------------------------
-- The site owner (James): adds schools. These do not show any student's data.
-- ---------------------------------------------------------------------------

-- Add a school and its first email domain. Returns the new school's number.
create function public.owner_add_school(school_name text, first_domain text, approved_on date default null)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_id integer;
begin
  perform public.require_site_owner();
  insert into public.schools (name, board_approved_on) values (school_name, approved_on) returning id into new_id;
  insert into public.school_domains (domain, school_id) values (lower(first_domain), new_id);
  return new_id;
end;
$$;

create function public.owner_add_school_domain(school integer, new_domain text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.require_site_owner();
  insert into public.school_domains (domain, school_id) values (lower(new_domain), school);
end;
$$;

-- Switch a school off (nobody from it can sign in or read anything) or back on.
create function public.owner_set_school_active(school integer, on_or_off boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.require_site_owner();
  update public.schools set active = on_or_off where id = school;
  if not found then
    raise exception 'There is no school with that number.' using errcode = '22023';
  end if;
end;
$$;

create function public.owner_set_school_contact(school integer, teacher uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.require_site_owner();
  if not exists (select 1 from public.profiles p where p.id = teacher and p.school_id = school and p.role = 'teacher') then
    raise exception 'That person isn''t a teacher at that school.' using errcode = '22023';
  end if;
  update public.schools set contact_teacher = teacher where id = school;
end;
$$;

-- The list of schools. Only counts, never a student's name or record.
create function public.owner_schools()
returns table(id integer, name text, active boolean, board_approved_on date, domains text[], students integer, teachers integer)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.require_site_owner();
  return query
  select s.id, s.name, s.active, s.board_approved_on,
         coalesce((select array_agg(d.domain order by d.domain) from public.school_domains d where d.school_id = s.id), '{}'),
         (select count(*)::integer from public.profiles p where p.school_id = s.id and p.role = 'student'),
         (select count(*)::integer from public.profiles p where p.school_id = s.id and p.role = 'teacher')
  from public.schools s order by s.id;
end;
$$;

