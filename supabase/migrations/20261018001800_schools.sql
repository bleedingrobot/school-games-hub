-- Make someone a school admin (and a teacher). They must have signed in once.
--   select public.make_school_admin('your.name@douglaspark.school.nz');
create function public.make_school_admin(email text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  account uuid;
begin
  select id into account from auth.users where lower(auth.users.email) = lower(make_school_admin.email);
  if account is null then
    raise exception 'No account with that email yet. Sign in to the website once first.';
  end if;
  update public.profiles set role = 'teacher', school_admin = true where id = account;
end;
$$;

-- Make someone the site owner (you). They must have signed in once.
--   select public.make_site_owner('your.name@douglaspark.school.nz');
create function public.make_site_owner(email text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  account uuid;
begin
  select id into account from auth.users where lower(auth.users.email) = lower(make_site_owner.email);
  if account is null then
    raise exception 'No account with that email yet. Sign in to the website once first.';
  end if;
  insert into public.site_owners (user_id) values (account) on conflict do nothing;
end;
$$;

