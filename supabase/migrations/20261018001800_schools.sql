-- New functions start locked (the first migration set that up), so each one the website needs
-- is granted here. Nothing earlier is revoked.
grant execute on function
  public.my_school(),
  public.same_school(uuid),
  public.is_school_admin(),
  public.is_site_owner(),
  public.my_school_info(),
  public.owner_add_school(text, text, date),
  public.owner_add_school_domain(integer, text),
  public.owner_set_school_active(integer, boolean),
  public.owner_set_school_contact(integer, uuid),
  public.owner_schools()
to authenticated;
grant execute on function public.hook_before_user_created(jsonb) to supabase_auth_admin;
grant execute on function public.pick_display_name(text, text), public.create_profile_for_new_user() to supabase_auth_admin;
grant execute on function public.is_school_email(text), public.school_for_email(text) to supabase_auth_admin;

-- >>> lock new functions
-- Supabase lets everyone (even a signed-out visitor) call a new function unless it is locked, so lock
-- every function this file made. The grants above and in the earlier migrations are the only way in.
do $$
declare
  f record;
begin
  for f in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname in (
      'create_profile_for_new_user',
      'is_school_admin',
      'is_school_email',
      'is_site_owner',
      'keep_profile_school',
      'make_school_admin',
      'make_site_owner',
      'my_school',
      'my_school_info',
      'owner_add_school',
      'owner_add_school_domain',
      'owner_schools',
      'owner_set_school_active',
      'owner_set_school_contact',
      'require_school_admin',
      'require_site_owner',
      'same_school',
      'school_for_email'
    )
  loop
    execute format('revoke execute on function %s from public, anon', f.sig);
  end loop;
end;
$$;
