--
-- 1. Two new columns on achievement_types:
--    - how: one plain sentence saying how to earn it ("Build 5 Farms on one island."). Shown under the name.
--    - tier: 1 easy, 2 medium, 3 hard, set by how big the goal is. The Achievement Hall (stage 2) draws them as
--      bronze, silver and gold frames.
